# One-time: stable public URL https://<Hostname> via a Cloudflare named tunnel (default kudiguard.theaicitadel.com).
#   .\scripts\setup_named_tunnel.ps1 [-Hostname kudiguard.theaicitadel.com]
# Safe for other tunnels on this PC: the existing ~/.cloudflared/cert.pem (another domain) is backed up before the
# browser login and restored afterwards. KudiGuard's certificate, tunnel credentials and config live in
# deploy\cloudflared\ (git- and docker-ignored). Wrong zone chosen at login? Delete deploy\cloudflared\cert.pem, re-run.
param([string]$Hostname = "kudiguard.theaicitadel.com", [string]$TunnelName = "kudiguard")
$ErrorActionPreference = "Stop"
$root = Resolve-Path "$PSScriptRoot\.."
$dir = Join-Path $root "deploy\cloudflared"
$cloudflared = Join-Path $root "tools\cloudflared\cloudflared.exe"
$defaultCert = Join-Path $env:USERPROFILE ".cloudflared\cert.pem"
$ourCert = Join-Path $dir "cert.pem"
$credentials = Join-Path $dir "tunnel.json"
$config = Join-Path $dir "kudiguard.yml"

function Invoke-Cloudflared([string[]]$arguments) {
    $output = & $cloudflared @arguments 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) { throw "cloudflared $($arguments[0..2] -join ' ') failed: $output" }
    return $output
}

if (-not (Test-Path $ourCert)) {
    $backup = "$defaultCert.before-kudiguard"
    if ((Test-Path $defaultCert) -and -not (Test-Path $backup)) { Move-Item $defaultCert $backup }
    try {
        Write-Host "A browser window opens: log in to Cloudflare and choose the zone for $Hostname."
        & $cloudflared tunnel login
        if ($LASTEXITCODE -ne 0 -or -not (Test-Path $defaultCert)) { throw "Cloudflare login did not complete" }
        Move-Item $defaultCert $ourCert -Force
    } finally {
        if (Test-Path $backup) { Move-Item $backup $defaultCert -Force }  # the other project's cert, untouched
    }
}

$found = Invoke-Cloudflared @("tunnel", "--origincert", $ourCert, "list", "--name", $TunnelName, "--output", "json") | ConvertFrom-Json
if (-not $found) {
    Invoke-Cloudflared @("tunnel", "--origincert", $ourCert, "create", "--credentials-file", $credentials, $TunnelName) | Out-Host
    $found = Invoke-Cloudflared @("tunnel", "--origincert", $ourCert, "list", "--name", $TunnelName, "--output", "json") | ConvertFrom-Json
} elseif (-not (Test-Path $credentials)) {
    throw "Tunnel '$TunnelName' exists but $credentials is missing: delete it in the Cloudflare dashboard (or 'cloudflared tunnel delete $TunnelName') and re-run."
}
$uuid = @($found)[0].id
if (-not $uuid) { throw "could not determine the tunnel id" }

$route = Invoke-Cloudflared @("tunnel", "--origincert", $ourCert, "route", "dns", "--overwrite-dns", $TunnelName, $Hostname)
$routed = [regex]::Match($route, "(?i)CNAME\s+(\S+)").Groups[1].Value.TrimEnd(".")
if ($routed -and $routed -ne $Hostname) {
    throw "DNS was routed as '$routed', not '$Hostname': the login certificate is for another zone. Delete $ourCert and re-run."
}

@"
# Generated by scripts\setup_named_tunnel.ps1 (git-ignored).
tunnel: $uuid
credentials-file: $credentials
no-autoupdate: true
ingress:
  - hostname: $Hostname
    service: http://127.0.0.1:8010
  - service: http_status:404
"@ | Out-File -Encoding utf8 $config
Write-Host "Done. Start with: .\scripts\watchdog.ps1 -Named   ->  https://$Hostname/readyz"
