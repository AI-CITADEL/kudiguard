VERDICT_HEADLINE: dict[Verdict, Msg] = {
    Verdict.LIKELY_SCAM: Msg.VERDICT_LIKELY_SCAM,
    Verdict.CAUTION: Msg.VERDICT_CAUTION,
    Verdict.NO_FLAGS: Msg.VERDICT_NO_FLAGS,
}


class Messages:
    def __init__(self, registry: LanguageRegistry) -> None:
        self._registry = registry

    def text(self, language: LanguageCode, key: Msg, /, **params: Any) -> str:
        """Render a fixed message. Values are inserted verbatim (single formatting pass).

        ``language`` and ``key`` are positional-only so templates may use ``{language}`` as a placeholder.
        """
        return self._registry.get(language).strings[key.value].format_map(params)
