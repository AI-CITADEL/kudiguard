"""Fixed user-facing text, per language. Templates live in ``data/languages/<code>.yaml`` under ``strings``.

Fixed text (consent, verdict headlines, buttons, errors) is never generated by the LLM: it must be exact,
reviewed by native speakers and identical every time. The registry validates at load time that every language
has every key with the same ``{placeholders}`` and that buttons fit WhatsApp's limit.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from kudiguard.domain import LanguageCode, Verdict
from kudiguard.languages import BUTTON_MAX_CHARS, LanguageRegistry

__all__ = ["BUTTON_MAX_CHARS", "VERDICT_HEADLINE", "Messages", "Msg"]


class Msg(StrEnum):
    WELCOME = "welcome"
    CHOOSE_LANGUAGE = "choose_language"
    LANGUAGE_MENU_BUTTON = "btn_language_menu"
    LANGUAGE_SET = "language_set"
    BETA_LANGUAGE = "beta_language"
    LISTENING = "listening"
    CHECKING = "checking"
    I_HEARD = "i_heard"
    VERDICT_LIKELY_SCAM = "verdict_likely_scam"
    VERDICT_CAUTION = "verdict_caution"
    VERDICT_NO_FLAGS = "verdict_no_flags"
    WHAT_TO_DO = "what_to_do"
    WHERE_TO_REPORT = "where_to_report"
    DISCLAIMER = "disclaimer"
    FEEDBACK_PROMPT = "feedback_prompt"
    FEEDBACK_THANKS = "feedback_thanks"
    BTN_HELPFUL = "btn_helpful"
    BTN_NOT_HELPFUL = "btn_not_helpful"
    BTN_WHAT_TO_DO = "btn_what_to_do"
    BTN_REPORT = "btn_report"
    BTN_WARN_FAMILY = "btn_warn_family"
    WARN_FAMILY_INTRO = "warn_family_intro"
    WARN_FAMILY_FOOTER = "warn_family_footer"
    GREETING_REPLY = "greeting_reply"
    NOT_UNDERSTOOD = "not_understood"
    AUDIO_TOO_LONG = "audio_too_long"
